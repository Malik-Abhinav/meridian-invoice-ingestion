describe('invoice review', () => {
  it('separates original OCR 53 from current values and shows findings and skipped checks', async () => {
    mockApi()
    const user = await enter(); await openInvoice(user)
    expect(screen.getAllByText('53').length).toBeGreaterThan(0)
    await user.click(screen.getByRole('tab', { name: 'Review & decisions' }))
    expect(screen.getByText('line extension mismatch')).toBeInTheDocument()
    expect(screen.getByText(/Approval is blocked/i)).toBeInTheDocument()
    await user.click(screen.getByRole('tab', { name: 'PDF & OCR' }))
    expect(screen.getByLabelText('Invoice field')).toBeInTheDocument()
    expect(screen.getByText('OCR citation inspector')).toBeInTheDocument()
  })
  it('preserves exact decimal text and expected revision in a correction', async () => {
    const api = mockApi()
    const user = await enter(); await openInvoice(user)
    await user.click(screen.getByRole('tab', { name: 'Corrections' }))
    const quantity = screen.getByRole('textbox', { name: 'Row 2 quantity' })
    await user.clear(quantity); await user.type(quantity, '3')
    const cost = screen.getByRole('textbox', { name: 'Row 2 unit cost' })
    await user.clear(cost); await user.type(cost, '7.5001')
    await user.click(screen.getByRole('button', { name: 'Save correction' }))
    await waitFor(() => expect(api.state().lastCorrection).toMatchObject({ expected_revision: 1, lines: [{ source_row_order: 2, quantity: 3, unit_cost: '7.5001' }] }))
    expect(JSON.stringify(api.state().lastCorrection)).not.toContain('7.5001,')
    expect(await screen.findByText(/Correction saved/i)).toBeInTheDocument()
  })
  it('submits signed printed money as text for server validation', async () => {
    const api = mockApi()
    const user = await enter(); await openInvoice(user)
    await user.click(screen.getByRole('tab', { name: 'Corrections' }))
    const printed = screen.getByRole('textbox', { name: 'Printed tax' })
    await user.clear(printed); await user.type(printed, '-0.5000')
    await user.click(screen.getByRole('button', { name: 'Save correction' }))
    await waitFor(() => expect(api.state().lastCorrection).toMatchObject({ expected_revision: 1, printed_tax: '-0.5000' }))
  })
  it('reports revision conflicts and asks before discarding unsaved edits', async () => {
    mockApi({ correctionConflict: true })
    const user = await enter(); await openInvoice(user)
    await user.click(screen.getByRole('tab', { name: 'Corrections' }))
    const quantity = screen.getByRole('textbox', { name: 'Row 2 quantity' })
    await user.clear(quantity); await user.type(quantity, '3')
    await user.click(screen.getByRole('button', { name: 'Save correction' }))
    expect(await screen.findByText(/revision_conflict from API/i)).toBeInTheDocument()
    await user.clear(quantity); await user.type(quantity, '4')
    await user.click(screen.getByRole('button', { name: 'Discard edits' }))
    expect(screen.getByRole('dialog', { name: /Discard unsaved corrections/i })).toBeInTheDocument()
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Cancel' }))
    expect(quantity).toHaveValue('4')
    await user.click(screen.getByRole('link', { name: 'Invoices' }))
    expect(screen.getByRole('dialog', { name: /Leave with unsaved corrections/i })).toBeInTheDocument()
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Cancel' }))
    expect(screen.getByRole('heading', { name: 'FICT_A-INV-0001' })).toBeInTheDocument()
  })
  it('shows unperformed checks and keeps posted invoices read-only', async () => {
    mockApi({ unperformed: true, initialStatus: 'posted' })
    const user = await enter(); await openInvoice(user)
    await user.click(screen.getByRole('tab', { name: 'Corrections' }))
    expect(screen.getByText(/Corrections are read-only/i)).toBeInTheDocument()
    await user.click(screen.getByRole('tab', { name: 'Review & decisions' }))
    expect(screen.getByText('supplier verification')).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: /Post receipt/i })).not.toBeInTheDocument()
  })
  it('requires explicit PO allocation, approval and posting confirmations, and reuses the posting key', async () => {
    const api = mockApi()
    const user = await enter(); await openInvoice(user)
    await user.click(screen.getByRole('tab', { name: 'Corrections' }))
    const quantity = screen.getByRole('textbox', { name: 'Row 2 quantity' })
    await user.clear(quantity); await user.type(quantity, '3')
    await user.click(screen.getByRole('button', { name: 'Save correction' }))
    await waitFor(() => expect(api.state().quantity).toBe(3))
    await user.click(screen.getByRole('tab', { name: 'Review & decisions' }))
    const approvalButton = screen.getByRole('button', { name: 'Review approval details' })
    await waitFor(() => expect(approvalButton).toBeEnabled())
    await user.type(screen.getByLabelText('Destination location ID'), IDS.location)
    await user.selectOptions(screen.getByLabelText('PO line for row 1'), IDS.po1)
    await user.selectOptions(screen.getByLabelText('PO line for row 2'), IDS.po2)
    await user.click(approvalButton)
    expect(screen.getByRole('dialog', { name: /Approve this invoice/i })).toBeInTheDocument()
    expect(api.state().lastApproval).toBeNull()
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Approve invoice' }))
    await waitFor(() => expect(api.state().status).toBe('approved'))
    expect(api.state().lastApproval).toMatchObject({ expected_revision: 2, location_id: IDS.location, allocations: [{ invoice_line_id: IDS.line1, purchase_order_line_id: IDS.po1, source_row_order: 1 }, { invoice_line_id: IDS.line2, purchase_order_line_id: IDS.po2, source_row_order: 2 }] })
    await user.click(await screen.findByRole('button', { name: 'Review posting action' }))
    expect(screen.getByRole('dialog', { name: /Post inventory receipt/i })).toBeInTheDocument()
    expect(api.state().postedKey).toBeNull()
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Post receipt' }))
    await waitFor(() => expect(api.state().status).toBe('posted'))
    const firstKey = api.state().postedKey
    expect(api.state().movements).toHaveLength(2)
    await user.click(await screen.findByRole('button', { name: 'Retry same posting request' }))
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Post receipt' }))
    expect((await screen.findAllByText(/already posted/i)).length).toBeGreaterThan(0)
    const postCalls = api.calls.filter(call => call.path.endsWith('/post'))
    expect(postCalls).toHaveLength(2)
    expect((postCalls[0].body as { idempotency_key: string }).idempotency_key).toBe(firstKey)
    expect((postCalls[1].body as { idempotency_key: string }).idempotency_key).toBe(firstKey)
    expect(api.state().movements).toHaveLength(2)
  })
  it('recovers persisted approval after refresh without another approval', async () => {
    const api = mockApi({ initialStatus: 'approved' })
    const user = await enter(); await openInvoice(user)
    await user.click(screen.getByRole('tab', { name: 'Review & decisions' }))
    expect(screen.getByText(IDS.location)).toBeInTheDocument()
    cleanup(); queryClient.clear(); await router.navigate(`/invoices/${IDS.invoice}`)
    const refreshed = userEvent.setup(); render(<App />)
    expect(screen.getByLabelText('Staff bearer token')).toBeInTheDocument()
    await refreshed.type(screen.getByLabelText('Staff bearer token'), 'valid-token')
    await refreshed.click(screen.getByRole('button', { name: 'Enter workspace' }))
    await screen.findByRole('heading', { name: 'FICT_A-INV-0001' })
    await refreshed.click(screen.getByRole('tab', { name: 'Review & decisions' }))
    expect(screen.getByText(IDS.location)).toBeInTheDocument()
    expect(screen.getByText(/Row 1 →/)).toBeInTheDocument()
    await refreshed.click(screen.getByRole('button', { name: 'Review posting action' }))
    await refreshed.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Post receipt' }))
    await waitFor(() => expect(api.state().status).toBe('posted'))
    expect(api.calls.filter(call => call.path.endsWith('/approve'))).toHaveLength(0)
    expect(api.state().movements).toHaveLength(2)
  })
  it('retains the posting key after a conflict and does not create receipts', async () => {
    const api = mockApi({ initialStatus: 'approved', postConflict: true })
    const user = await enter(); await openInvoice(user)
    await user.click(screen.getByRole('tab', { name: 'Review & decisions' }))
    await user.click(screen.getByRole('button', { name: 'Review posting action' }))
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Post receipt' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('po_ineligible')
    await user.click(screen.getByRole('button', { name: 'Retry same posting request' }))
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Post receipt' }))
    await waitFor(() => expect(api.calls.filter(call => call.path.endsWith('/post'))).toHaveLength(2))
    const keys = api.calls.filter(call => call.path.endsWith('/post')).map(call => (call.body as { idempotency_key: string }).idempotency_key)
    expect(keys[0]).toBe(keys[1])
    expect(api.state().movements).toHaveLength(0)
  })
  it('recovers the same pending posting key after refresh', async () => {
    const api = mockApi({ initialStatus: 'approved', postConflict: true })
    const user = await enter(); await openInvoice(user)
    await user.click(screen.getByRole('tab', { name: 'Review & decisions' }))
    await user.click(screen.getByRole('button', { name: 'Review posting action' }))
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Post receipt' }))
    await screen.findByRole('alert')
    const first = (api.calls.find(call => call.path.endsWith('/post'))?.body as { idempotency_key: string }).idempotency_key
    cleanup(); queryClient.clear(); await router.navigate(`/invoices/${IDS.invoice}`)
    const refreshed = userEvent.setup(); render(<App />)
    await refreshed.type(screen.getByLabelText('Staff bearer token'), 'valid-token')
    await refreshed.click(screen.getByRole('button', { name: 'Enter workspace' }))
    await screen.findByRole('heading', { name: 'FICT_A-INV-0001' })
    await refreshed.click(screen.getByRole('tab', { name: 'Review & decisions' }))
    await refreshed.click(screen.getByRole('button', { name: 'Review posting action' }))
    await refreshed.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Post receipt' }))
    await waitFor(() => expect(api.calls.filter(call => call.path.endsWith('/post'))).toHaveLength(2))
    const second = (api.calls.filter(call => call.path.endsWith('/post'))[1].body as { idempotency_key: string }).idempotency_key
    expect(second).toBe(first)
    expect(api.state().movements).toHaveLength(0)
  })
  it('requires rejection reason and confirmation before calling the API', async () => {
    const api = mockApi()
    const user = await enter(); await openInvoice(user)
    await user.click(screen.getByRole('tab', { name: 'Review & decisions' }))
    await user.type(screen.getByLabelText('Reason for rejection'), 'Document is unreadable')
    await user.click(screen.getByRole('button', { name: 'Review rejection' }))
    expect(screen.getByRole('dialog', { name: /Reject this invoice/i })).toBeInTheDocument()
    expect(api.state().status).toBe('review_required')
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Reject invoice' }))
    await waitFor(() => expect(api.state().status).toBe('rejected'))
    expect(api.calls.find(call => call.path.endsWith('/reject'))?.body).toMatchObject({ expected_revision: 1, reason: 'Document is unreadable' })
  })
})
