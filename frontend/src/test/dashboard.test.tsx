import { beforeEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App, { queryClient, router } from '../App'
import { ApiClient, ApiError, retryRead } from '../api/client'
import { IDS, mockApi } from './mockApi'

beforeEach(async () => { vi.unstubAllGlobals(); queryClient.clear(); sessionStorage.clear(); await router.navigate('/') })
async function enter() { const user = userEvent.setup(); render(<App />); await user.type(screen.getByLabelText('Staff bearer token'), 'valid-token'); await user.click(screen.getByRole('button', { name: 'Enter workspace' })); await screen.findByRole('heading', { name: 'Invoice command center' }); return user }
async function openInvoice(user: ReturnType<typeof userEvent.setup>) { await user.click(screen.getByRole('link', { name: 'Invoices' })); await screen.findByText('Invoice records'); await user.click(await screen.findByRole('link', { name: /Open/i })); await screen.findByRole('heading', { name: 'FICT_A-INV-0001' }) }

describe('staff session and API client', () => {
  it('requires an in-memory bearer token and rejects an invalid token', async () => {
    const api = mockApi({ invalidToken: true })
    const user = userEvent.setup(); render(<App />)
    expect(screen.getByRole('heading', { name: /Staff review/i })).toBeInTheDocument()
    await user.type(screen.getByLabelText('Staff bearer token'), 'invalid')
    await user.click(screen.getByRole('button', { name: 'Enter workspace' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('invalid_credentials')
    expect(screen.getByLabelText('Staff bearer token')).toHaveValue('invalid')
    expect(api.calls.some(call => call.authorization === 'Bearer invalid')).toBe(true)
    expect(api.calls.every(call => !call.path.includes('valid-token'))).toBe(true)
  })
  it('captures correlation IDs and never retries unsafe mutations', async () => {
    mockApi({ uploadError: true })
    const client = new ApiClient(() => 'valid-token', () => undefined)
    await expect(client.upload(new File(['bad'], 'bad.pdf', { type: 'application/pdf' }))).rejects.toMatchObject({ status: 400, code: 'invalid_pdf', correlationId: 'test-correlation' })
    expect(retryRead(0, new ApiError(409, 'conflict', 'Conflict'))).toBe(false)
    expect(retryRead(0, new ApiError(503, 'unavailable', 'Unavailable'))).toBe(true)
  })
  it('clears protected state on sign out', async () => {
    mockApi()
    const user = await enter()
    sessionStorage.setItem(`meridian.posting.${IDS.invoice}`, 'pending-key')
    await user.click(screen.getByRole('button', { name: 'Sign out' }))
    expect(screen.getByLabelText('Staff bearer token')).toBeInTheDocument()
    expect(queryClient.getQueryData(['invoices', { limit: 100, offset: 0 }])).toBeUndefined()
    expect(sessionStorage.getItem(`meridian.posting.${IDS.invoice}`)).toBeNull()
  })
  it('keeps a 403 document denial visible without discarding a valid session', async () => {
    mockApi({ forbiddenDocument: true })
    const user = await enter(); await openInvoice(user)
    await user.click(screen.getByRole('tab', { name: 'PDF & OCR' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('staff_forbidden')
    expect(screen.getByRole('button', { name: 'Sign out' })).toBeInTheDocument()
  })
  it('invalidates the session and cached reads after a later 401', async () => {
    mockApi({ expireAfterProbe: true })
    const user = userEvent.setup(); render(<App />)
    await user.type(screen.getByLabelText('Staff bearer token'), 'valid-token')
    await user.click(screen.getByRole('button', { name: 'Enter workspace' }))
    expect(await screen.findByText(/staff session was rejected or expired/i)).toBeInTheDocument()
    expect(screen.queryByRole('heading', { name: 'Invoice command center' })).not.toBeInTheDocument()
    expect(queryClient.getQueryData(['invoices', { limit: 100, offset: 0 }])).toBeUndefined()
  })
  it('revokes the authenticated PDF object URL on sign-out', async () => {
    const previousCreate = URL.createObjectURL, previousRevoke = URL.revokeObjectURL
    const create = vi.fn(() => 'blob:meridian-test'), revoke = vi.fn()
    Object.defineProperty(URL, 'createObjectURL', { configurable: true, value: create })
    Object.defineProperty(URL, 'revokeObjectURL', { configurable: true, value: revoke })
    try {
      mockApi()
      const user = await enter(); await openInvoice(user)
      await waitFor(() => expect(create).toHaveBeenCalled())
      await user.click(screen.getByRole('button', { name: 'Sign out' }))
      await waitFor(() => expect(revoke).toHaveBeenCalledWith('blob:meridian-test'))
    } finally {
      if (previousCreate) Object.defineProperty(URL, 'createObjectURL', { configurable: true, value: previousCreate })
      else Reflect.deleteProperty(URL, 'createObjectURL')
      if (previousRevoke) Object.defineProperty(URL, 'revokeObjectURL', { configurable: true, value: previousRevoke })
      else Reflect.deleteProperty(URL, 'revokeObjectURL')
    }
  })
})

